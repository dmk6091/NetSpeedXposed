    private static double[][] sLon, sLat;   // per polyline

    private static synchronized void load() {
        if (sLon != null) return;
        byte[] b = android.util.Base64.decode(DATA, android.util.Base64.DEFAULT);
        int[] pos = {0};
        java.util.ArrayList<double[]> xs = new java.util.ArrayList<>(), ys = new java.util.ArrayList<>();
        while (pos[0] < b.length) {
            int n = (int) rd(b, pos);
            double[] x = new double[n], y = new double[n];
            long px = 0, py = 0;
            for (int i = 0; i < n; i++) {
                px += rd(b, pos);
                py += rd(b, pos);
                x[i] = px / 1e4;
                y[i] = py / 1e4;
            }
            xs.add(x);
            ys.add(y);
        }
        sLat = ys.toArray(new double[0][]);
        sLon = xs.toArray(new double[0][]);
    }

    private static long rd(byte[] b, int[] pos) {
        long v = 0;
        int s = 0;
        while (true) {
            int c = b[pos[0]++] & 0xff;
            v |= (long) (c & 0x7f) << s;
            if ((c & 0x80) == 0) break;
            s += 7;
        }
        return (v >>> 1) ^ -(v & 1);
    }

    /** Straight-line distance in km to the nearest coastline, or -1 when the data can't be read. */
    static double distanceKm(double lat, double lon) {
        try {
            load();
            double k = Math.cos(Math.toRadians(lat)) * 111.195, best = 1e9;
            for (int l = 0; l < sLon.length; l++) {
                double[] x = sLon[l], y = sLat[l];
                for (int i = 0; i + 1 < x.length; i++) {
                    double ax = (x[i] - lon) * k, ay = (y[i] - lat) * 111.195;
                    double bx = (x[i + 1] - lon) * k, by = (y[i + 1] - lat) * 111.195;
                    // cheap skip: both ends farther than the best in the same direction
                    if (ax > best && bx > best) continue;
                    if (ax < -best && bx < -best) continue;
                    if (ay > best && by > best) continue;
                    if (ay < -best && by < -best) continue;
                    double dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
                    double t = len == 0 ? 0 : Math.max(0, Math.min(1, (-ax * dx - ay * dy) / len));
                    double d = Math.hypot(ax + t * dx, ay + t * dy);
                    if (d < best) best = d;
                }
            }
            return best >= 1e8 ? -1 : best;
        } catch (Throwable t) {
            return -1;
        }
    }

    /** The nearest point on the coastline {lat, lon}, or null when the data can't be read. */
    static double[] nearestPoint(double lat, double lon, double[][] near, double maxKm) {
        try {
            load();
            double k = Math.cos(Math.toRadians(lat)) * 111.195, best = 1e9, bx0 = 0, by0 = 0;
            for (int l = 0; l < sLon.length; l++) {
                double[] x = sLon[l], y = sLat[l];
                for (int i = 0; i + 1 < x.length; i++) {
                    double ax = (x[i] - lon) * k, ay = (y[i] - lat) * 111.195;
                    double bx = (x[i + 1] - lon) * k, by = (y[i + 1] - lat) * 111.195;
                    if (ax > best && bx > best) continue;
                    if (ax < -best && bx < -best) continue;
                    if (ay > best && by > best) continue;
                    if (ay < -best && by < -best) continue;
                    double dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
                    double t = len == 0 ? 0 : Math.max(0, Math.min(1, (-ax * dx - ay * dy) / len));
                    double px = ax + t * dx, py = ay + t * dy, d = Math.hypot(px, py);
                    if (d >= best) continue;
                    // open coast only: the piece must lie near one of the given open-sea points (creeks and river mouths are far from all of them)
                    double mlat = lat + py / 111.195, mlon = lon + px / k;
                    boolean ok = false;
                    for (double[] q : near) {
                        double ex = (q[1] - mlon) * k, ey = (q[0] - mlat) * 111.195;
                        if (ex * ex + ey * ey < maxKm * maxKm) { ok = true; break; }
                    }
                    if (!ok) continue;
                    if (d < best) { best = d; bx0 = px; by0 = py; }
                }
            }
            return best >= 1e8 ? null : new double[]{lat + by0 / 111.195, lon + bx0 / k};
        } catch (Throwable t) {
            return null;
        }
    }
