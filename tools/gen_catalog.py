#!/usr/bin/env python3
"""Reads SettingsActivity.java and writes SettingsCatalog.java: the list of switches and sliders,
so the ROM Settings page (hook) always shows the same options as the NetSpeed settings screen.
usage: gen_catalog.py <dir with SettingsActivity.java>"""
import re, sys, os

d = sys.argv[1]
src = open(os.path.join(d, 'SettingsActivity.java'), encoding='utf-8').read()

def args_at(s, i):
    """text of the call arguments starting right after '(' at s[i-1]; returns (list of arg strings, end index)"""
    depth, j, cur, out, instr = 1, i, [], [], False
    while j < len(s):
        ch = s[j]
        if instr:
            cur.append(ch)
            if ch == '\\':
                cur.append(s[j + 1]); j += 1
            elif ch == '"':
                instr = False
        else:
            if ch == '"':
                instr = True; cur.append(ch)
            elif ch == '(':
                depth += 1; cur.append(ch)
            elif ch == ')':
                depth -= 1
                if depth == 0:
                    out.append(''.join(cur).strip()); return out, j
                cur.append(ch)
            elif ch == ',' and depth == 1:
                out.append(''.join(cur).strip()); cur = []
            else:
                cur.append(ch)
        j += 1
    raise ValueError('unbalanced')

items = []
for m in re.finditer(r'\b(section|toggle|slider|textField|predictToggle)\((c\b(, )?)?', src):
    kind = m.group(1)
    line_start = src.rfind('\n', 0, m.start()) + 1
    if 'private void' in src[line_start:m.start()]:
        continue
    if kind != 'section' and not m.group(2):
        continue
    a, _ = args_at(src, m.end())
    if kind == 'section' and len(a) == 1:
        items.append(('sec', a))
        if a[0] == '"Updates"':
            items.append(('U', []))           # update check: opens the app
    elif kind == 'predictToggle':
        items.append(('P', []))               # app suggestions: needs root in the app, opens it
    elif kind == 'textField' and len(a) == 5 and a[4] == 'false':
        items.append(('E', a[0:4]))           # label, desc, key, hint (tokens stay in the app)
    elif kind == 'toggle' and len(a) == 4:
        items.append(('T', a))
    elif kind == 'slider' and len(a) == 6:
        items.append(('S', a))

out = ['package com.netspeed.xposed;', '',
       '/** Generated by tools/gen_catalog.py from SettingsActivity.java. Do not edit. */',
       'final class SettingsCatalog {', '    private SettingsCatalog() {}', '',
       '    static java.util.List<Object[]> items() {',
       '        java.util.List<Object[]> l = new java.util.ArrayList<>();']
for kind, a in items:
    out.append('        l.add(new Object[]{%s});' % ', '.join(['"%s"' % kind] + list(a)))
out += ['        return l;', '    }', '}', '']
open(os.path.join(d, 'SettingsCatalog.java'), 'w', encoding='utf-8').write('\n'.join(out))
print('catalog items:', len(items))
